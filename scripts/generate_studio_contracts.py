def typescript(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    choices = schema.get("enum", [schema["const"]] if "const" in schema else [])
    if choices:
        return " | ".join(json.dumps(item) for item in choices)
    if "anyOf" in schema or "oneOf" in schema:
        return " | ".join(typescript(item) for item in schema.get("anyOf", schema.get("oneOf")))
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript(schema.get('items', {}))}>"
    if kind == "object":
        if "properties" in schema:
            # Serialized models always include defaulted fields.
            result = (
                "{\n"
                + "\n".join(f"  {json.dumps(key)}: {typescript(value)};" for key, value in schema["properties"].items())
                + "\n}"
            )
        else:
            additional = schema.get("additionalProperties", {})
            result = f"Record<string, {typescript(additional) if isinstance(additional, dict) else 'unknown'}>"
        return result
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def render():
    definitions = {}
    for model in MODELS:
        schema = TypeAdapter(model).json_schema(mode="serialization")
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    return (
        "// Generated by scripts/generate_studio_contracts.py; do not edit.\n\n"
        + "\n\n".join(f"export type {name} = {typescript(schema)};" for name, schema in sorted(definitions.items()))
        + "\n"
    )


def render_jobs():
    """Export the default service contracts for the browser-only Playground catalog."""
    root = OUTPUT.parents[4]
    jobs = yaml.safe_load((root / "axonx/app/config/default.yaml").read_text(encoding="utf-8"))["jobs"]
    contracts = {}
    for name, values in sorted(jobs.items()):
        config = JobConfig.model_validate(values)
        if config.enable_serve:
            contracts[name] = JobInfo(
                name=name,
                description=config.description,
                input_schema=config.parameters,
                output_schema=JobResponse.model_json_schema(),
            ).model_dump(mode="json")
    return json.dumps({"version": __version__, "jobs": contracts}, ensure_ascii=False, indent=2) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    # Match repository formatting so generation is deterministic.
    for output, source, language in ((OUTPUT, render(), "typescript"), (JOB_OUTPUT, render_jobs(), "json")):
        content = subprocess.run(
            ["npx", "--no-install", "prettier", "--parser", language],
            input=source,
            text=True,
            capture_output=True,
            check=True,
            cwd=OUTPUT.parents[3],
        ).stdout
        if args.check:
            if not output.exists() or output.read_text(encoding="utf-8") != content:
                raise SystemExit("Studio contracts are stale; run python -m scripts.generate_studio_contracts")
        else:
            output.write_text(content, encoding="utf-8")
